-- Dọn dẹp các bảng cũ nếu đã tồn tại (theo thứ tự khóa ngoại)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOGS', 'MEDICAL_RECORDS', 'ADMISSIONS', 'APPOINTMENTS',
        'REFERRALS', 'BEDS', 'ROOMS', 'DOCTORS', 'DEPARTMENTS',
        'PATIENTS', 'HOSPITALS', 'SYMPTOM_KNOWLEDGE', 'MEDICAL_DOCUMENTS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- 1. BẢNG BỆNH VIỆN (HOSPITALS) - Đỉnh chính trong mô hình đồ thị chuyển tuyến
CREATE TABLE hospitals (
    hospital_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    code          VARCHAR2(30) NOT NULL UNIQUE,
    name          VARCHAR2(200) NOT NULL,
    level_name    VARCHAR2(50),
    province      VARCHAR2(100),
    address       VARCHAR2(300),
    created_at    TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. BẢNG KHOA / PHÒNG BAN (DEPARTMENTS)
CREATE TABLE departments (
    department_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    hospital_id   NUMBER NOT NULL REFERENCES hospitals(hospital_id) ON DELETE CASCADE,
    code          VARCHAR2(30) NOT NULL,
    name          VARCHAR2(150) NOT NULL,
    specialty     VARCHAR2(150),
    CONSTRAINT uq_department UNIQUE (hospital_id, code)
);

-- 3. BẢNG BÁC SĨ (DOCTORS)
CREATE TABLE doctors (
    doctor_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    department_id NUMBER NOT NULL REFERENCES departments(department_id),
    full_name     VARCHAR2(150) NOT NULL,
    license_no    VARCHAR2(50) NOT NULL UNIQUE,
    phone         VARCHAR2(30),
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT ck_doctors_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'ON_LEAVE'))
);

-- 4. BẢNG BỆNH NHÂN (PATIENTS) - BR01: medical_code duy nhất
CREATE TABLE patients (
    patient_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    medical_code VARCHAR2(30) NOT NULL UNIQUE,
    full_name    VARCHAR2(150) NOT NULL,
    dob          DATE,
    gender       VARCHAR2(20),
    phone        VARCHAR2(30),
    address      VARCHAR2(300),
    created_at   TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_patients_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER', 'Nam', 'Nữ', 'Khác'))
);

-- 5. BẢNG PHÒNG BỆNH (ROOMS)
CREATE TABLE rooms (
    room_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    department_id NUMBER NOT NULL REFERENCES departments(department_id),
    room_number   VARCHAR2(40) NOT NULL,
    room_type     VARCHAR2(100),
    floor_no      NUMBER(4,0),
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT uq_rooms_dept_number UNIQUE (department_id, room_number),
    CONSTRAINT ck_rooms_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE'))
);

-- 6. BẢNG GIƯỜNG BỆNH (BEDS) - BR03: Kiểm soát trạng thái giường phục vụ phân giường an toàn
CREATE TABLE beds (
    bed_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    room_id       NUMBER REFERENCES rooms(room_id) ON DELETE CASCADE,
    department_id NUMBER NOT NULL REFERENCES departments(department_id),
    bed_code      VARCHAR2(40) NOT NULL,
    status        VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT ck_beds_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE', 'INACTIVE'))
);

-- 7. BẢNG LỊCH HẸN KHÁM (APPOINTMENTS) - BR02: Chặn đặt trùng lịch bác sĩ cùng giờ
CREATE TABLE appointments (
    appointment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    patient_id     NUMBER NOT NULL REFERENCES patients(patient_id),
    doctor_id      NUMBER REFERENCES doctors(doctor_id),
    department_id  NUMBER NOT NULL REFERENCES departments(department_id),
    scheduled_at   TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    end_at         TIMESTAMP(6) WITH LOCAL TIME ZONE,
    status         VARCHAR2(25) DEFAULT 'CONFIRMED' NOT NULL,
    symptoms       CLOB,
    priority       VARCHAR2(20) DEFAULT 'NORMAL',
    created_at     TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_appt_doc_start UNIQUE (doctor_id, scheduled_at),
    CONSTRAINT ck_appt_status CHECK (status IN ('CREATED', 'CONFIRMED', 'CHECKED_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW'))
);

-- 8. BẢNG NHẬP VIỆN / PHÂN GIƯỜNG (ADMISSIONS)
CREATE TABLE admissions (
    admission_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    patient_id     NUMBER NOT NULL REFERENCES patients(patient_id),
    bed_id         NUMBER REFERENCES beds(bed_id),
    admitted_at    TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    discharged_at  TIMESTAMP(6) WITH LOCAL TIME ZONE,
    status         VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at     TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_admissions_status CHECK (status IN ('ACTIVE', 'DISCHARGED', 'TRANSFERRED', 'CANCELLED'))
);

-- 9. BẢNG CHUYỂN TUYẾN (REFERRALS) - BR05: Cạnh đồ thị (from_hospital_id <> to_hospital_id)
CREATE TABLE referrals (
    referral_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    patient_id            NUMBER NOT NULL REFERENCES patients(patient_id),
    from_hospital_id      NUMBER NOT NULL REFERENCES hospitals(hospital_id),
    to_hospital_id        NUMBER NOT NULL REFERENCES hospitals(hospital_id),
    referred_by_doctor_id NUMBER REFERENCES doctors(doctor_id),
    reason                CLOB,
    urgency               VARCHAR2(20) DEFAULT 'NORMAL' NOT NULL,
    status                VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    referral_time         TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    accepted_at           TIMESTAMP(6) WITH LOCAL TIME ZONE,
    completed_at          TIMESTAMP(6) WITH LOCAL TIME ZONE,
    CONSTRAINT ck_ref_hosp_diff CHECK (from_hospital_id <> to_hospital_id),
    CONSTRAINT ck_ref_urgency CHECK (urgency IN ('NORMAL', 'URGENT', 'EMERGENCY')),
    CONSTRAINT ck_ref_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COMPLETED', 'CANCELLED'))
);

-- 10. BẢNG HỒ SƠ BỆNH ÁN JSON (MEDICAL_RECORDS) - Oracle 23ai Native JSON
CREATE TABLE medical_records (
    record_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    patient_id        NUMBER NOT NULL REFERENCES patients(patient_id),
    appointment_id    NUMBER REFERENCES appointments(appointment_id),
    doctor_id         NUMBER NOT NULL REFERENCES doctors(doctor_id),
    diagnosis_summary VARCHAR2(1000),
    record_json       JSON NOT NULL,
    created_at        TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- 11. BẢNG NHẬT KÝ KIỂM TOÁN (AUDIT_LOGS) - Tự động ghi vết JSON thay đổi
CREATE TABLE audit_logs (
    log_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    entity_name      VARCHAR2(128) NOT NULL,
    action           VARCHAR2(20) NOT NULL,
    entity_id        NUMBER NOT NULL,
    actor_identifier VARCHAR2(128) DEFAULT 'SYSTEM',
    old_data         JSON,
    new_data         JSON,
    created_at       TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_audit_action CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'VIEW', 'EXPORT'))
);

-- 12. BẢNG TRI THỨC TRIỆU CHỨNG (SYMPTOM_KNOWLEDGE) - Oracle 23ai AI Vector Search 384 chiều
CREATE TABLE symptom_knowledge (
    symptom_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    name         VARCHAR2(200) NOT NULL,
    description  VARCHAR2(2000) NOT NULL,
    embedding    VECTOR(384, FLOAT32)
);

-- 13. BẢNG TÀI LIỆU Y KHOA (MEDICAL_DOCUMENTS) - Oracle 23ai AI Vector Search 384 chiều
CREATE TABLE medical_documents (
    doc_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100) PRIMARY KEY,
    title        VARCHAR2(500) NOT NULL,
    category     VARCHAR2(100),
    source_name  VARCHAR2(300),
    content      CLOB NOT NULL,
    embedding    VECTOR(384, FLOAT32),
    created_at   TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- Các Foreign Key Indexes cơ bản để tối ưu join
CREATE INDEX ix_departments_hosp ON departments (hospital_id);
CREATE INDEX ix_doctors_dept ON doctors (department_id);
CREATE INDEX ix_beds_dept ON beds (department_id, status);
CREATE INDEX ix_appt_patient ON appointments (patient_id);
CREATE INDEX ix_appt_dept ON appointments (department_id);
CREATE INDEX ix_admissions_patient ON admissions (patient_id);
CREATE INDEX ix_admissions_bed ON admissions (bed_id);
CREATE INDEX ix_referrals_patient ON referrals (patient_id);
CREATE INDEX ix_referrals_from_hosp ON referrals (from_hospital_id);
CREATE INDEX ix_referrals_to_hosp ON referrals (to_hospital_id);
CREATE INDEX ix_mrec_patient ON medical_records (patient_id);
CREATE INDEX ix_audit_entity ON audit_logs (entity_name, entity_id);

COMMIT;
